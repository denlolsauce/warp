"""S3-compatible artifact store.

Artifact identity is (storage key, sha256). Keys are durable; access URLs are
temporary and generated by the web app, never here. Stage outputs are laid out
under runs/{run_id}/{stage}/ so a resumed run can detect completed stages.
"""

import hashlib
import json
import logging
from dataclasses import dataclass
from pathlib import Path
from typing import Protocol

logger = logging.getLogger(__name__)


def sha256_file(path: Path, chunk_size: int = 1 << 20) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as f:
        while chunk := f.read(chunk_size):
            digest.update(chunk)
    return digest.hexdigest()


@dataclass(frozen=True)
class StoredArtifact:
    """Result of persisting one artifact."""

    storage_key: str
    checksum_sha256: str
    size_bytes: int
    content_type: str


class ObjectStore(Protocol):
    """Minimal S3 interface (satisfied by boto3 client wrappers and fakes)."""

    def put_object(self, key: str, data: bytes, content_type: str) -> None: ...

    def upload_file(self, path: Path, key: str, content_type: str) -> None: ...

    def download_file(self, key: str, path: Path) -> None: ...

    def exists(self, key: str) -> bool: ...

    def get_object(self, key: str) -> bytes: ...


class S3ObjectStore:
    """boto3-backed store. Bucket stays private; no public ACLs, ever."""

    def __init__(self, client, bucket: str):
        self._client = client
        self._bucket = bucket

    def put_object(self, key: str, data: bytes, content_type: str) -> None:
        self._client.put_object(Bucket=self._bucket, Key=key, Body=data, ContentType=content_type)

    def upload_file(self, path: Path, key: str, content_type: str) -> None:
        self._client.upload_file(str(path), self._bucket, key, ExtraArgs={"ContentType": content_type})

    def download_file(self, key: str, path: Path) -> None:
        path.parent.mkdir(parents=True, exist_ok=True)
        self._client.download_file(self._bucket, key, str(path))

    def exists(self, key: str) -> bool:
        try:
            self._client.head_object(Bucket=self._bucket, Key=key)
            return True
        except Exception:
            return False

    def get_object(self, key: str) -> bytes:
        return self._client.get_object(Bucket=self._bucket, Key=key)["Body"].read()


class InMemoryObjectStore:
    """Test double with identical semantics."""

    def __init__(self):
        self.objects: dict[str, tuple[bytes, str]] = {}

    def put_object(self, key: str, data: bytes, content_type: str) -> None:
        self.objects[key] = (data, content_type)

    def upload_file(self, path: Path, key: str, content_type: str) -> None:
        self.objects[key] = (path.read_bytes(), content_type)

    def download_file(self, key: str, path: Path) -> None:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(self.objects[key][0])

    def exists(self, key: str) -> bool:
        return key in self.objects

    def get_object(self, key: str) -> bytes:
        return self.objects[key][0]


def store_artifact(store: ObjectStore, path: Path, key: str, content_type: str) -> StoredArtifact:
    """Upload one file and return its durable identity."""
    checksum = sha256_file(path)
    store.upload_file(path, key, content_type)
    return StoredArtifact(
        storage_key=key,
        checksum_sha256=checksum,
        size_bytes=path.stat().st_size,
        content_type=content_type,
    )


# --- stage completion markers (idempotent resume) --------------------------

def stage_marker_key(run_id: str, stage: str) -> str:
    return f"runs/{run_id}/{stage}/_complete.json"


def stage_is_complete(store: ObjectStore, run_id: str, stage: str) -> bool:
    return store.exists(stage_marker_key(run_id, stage))


def read_stage_marker(store: ObjectStore, run_id: str, stage: str) -> dict:
    return json.loads(store.get_object(stage_marker_key(run_id, stage)).decode("utf-8"))


def write_stage_marker(store: ObjectStore, run_id: str, stage: str, outputs: dict) -> None:
    """Record a stage's outputs so a resumed run reuses them instead of recomputing.

    Written last, after every artifact of the stage is durably stored — the
    marker's existence is the completion contract.
    """
    store.put_object(
        stage_marker_key(run_id, stage),
        json.dumps(outputs, sort_keys=True).encode("utf-8"),
        "application/json",
    )
